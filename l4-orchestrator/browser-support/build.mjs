import { build } from 'esbuild';
import { copyFile, readFile } from 'node:fs/promises';

// WAI-ARIA 1.2 concrete roles. Unknown/abstract tokens must not hide a valid
// fallback role. Apply the same correction to getRole AND name computation.
// https://www.w3.org/TR/wai-aria-1.2/#role_definitions
const roles = `alert alertdialog application article banner blockquote button caption cell
checkbox code columnheader combobox complementary contentinfo definition deletion dialog
directory document emphasis feed figure form generic grid gridcell group heading img insertion
link list listbox listitem log main marquee math meter menu menubar menuitem menuitemcheckbox
menuitemradio navigation none note option paragraph presentation progressbar radio radiogroup
region row rowgroup rowheader scrollbar search searchbox separator slider spinbutton status
strong subscript superscript switch tab table tablist tabpanel term textbox time timer toolbar
tooltip tree treegrid treeitem`.split(/\s+/);

const roleFallback = {
  name: 'aria-role-fallback',
  setup(builder) {
    builder.onLoad({ filter: /[\\/]dom-accessibility-api[\\/]dist[\\/]getRole\.mjs$/ }, async ({ path }) => {
      const source = await readFile(path, 'utf8');
      const original = 'role.trim().split(" ")[0]';
      if (!source.includes(original)) throw new Error('Review role fallback patch against the new dependency');
      const contents = `const concreteRoles = new Set(${JSON.stringify(roles)});\n` +
        source.replace(original, '(role.trim().split(/\\s+/).find(token => concreteRoles.has(token)) || "")');
      return { contents, loader: 'js' };
    });
  },
};

await build({
  entryPoints: ['element_registry.js'],
  bundle: true,
  format: 'iife',
  globalName: 'L4Elements',
  platform: 'browser',
  target: 'es2021',
  plugins: [roleFallback],
  outfile: '../src/l4_orchestrator/_browser/elements.js',
  banner: { js: '// Generated by browser-support/build.mjs. dom-accessibility-api 0.7.1 (MIT); see LICENSE-dom-accessibility-api.md.' },
});
await copyFile('node_modules/dom-accessibility-api/LICENSE.md',
  '../src/l4_orchestrator/_browser/LICENSE-dom-accessibility-api.md');
