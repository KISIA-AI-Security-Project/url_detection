# --- 브랜드 6자 이상일 때만 적용 --------------------------------------------
#
# n과 m을 한 부류로 묶는 접기. 관측 81건으로 i/l 다음가는 빈도지만, 5자 브랜드
# naver가 영어 형태소 'maver-'와 충돌해 오귀속을 만든다(superprimavera,
# appsmavericks, maverickinfotec 등 10건 전량). 6자 이상으로 제한하면 이 충돌이
# 사라지고 amazon·instagram은 그대로 잡힌다.
#
# 시퀀스가 m이 아니라 n으로 접히는 이유: 관측된 현상은 rn·nn이 m으로 보이는 것이지만,
# 문자 매핑에 m -> n이 있어 부류의 대표는 n이다. 대표 문자로 바로 접어야 정규화가
# 멱등해진다. m으로 접으면 'rnn'처럼 두 규칙이 겹치는 입력에서 적용 순서에 따라
# 결과가 갈린다(rn 먼저 -> annazon / nn 먼저 -> arnazon). n으로 접으면 어느
# 순서로 적용해도 anazon으로 수렴한다.
NM_FOLD_SEQUENCES: tuple[tuple[str, str], ...] = (
    ("rn", "n"),   # arnazon -> anazon (관측 5건)
    ("nn", "n"),   # annazon -> anazon (관측 1건)
)
NM_FOLD_MAP: dict[str, str] = {"m": "n"}


